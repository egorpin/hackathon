const {chromium}=require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const fs=require('node:fs');
const assert=require('node:assert/strict');

(async()=>{
  const output='client/test-results/hud-settings';
  fs.mkdirSync(output,{recursive:true});
  const browser=await chromium.launch({channel:'msedge',headless:true,args:['--enable-webgl','--ignore-gpu-blocklist']});
  try {
    const page=await browser.newPage({viewport:{width:1440,height:960}}),errors=[];
    page.on('pageerror',error=>errors.push(error.message));
    await page.route('**/api/agent/messages',route=>route.fulfill({json:{messages:[]}}));
    const url=(process.env.MARS_TEST_URL || 'http://localhost:5173')+'/?fixture';
    const screenshot=name=>page.screenshot({path:`${output}/${name}.png`});
    const closeLobby=async()=>{
      await page.locator('.lobby-close').waitFor({state:'visible'});
      await page.locator('.lobby-close').click();
      await page.locator('.player-lobby').waitFor({state:'hidden'});
    };
    const selected=()=>page.locator('#build-hotbar [aria-pressed="true"]').count();
    const focusGame=()=>page.locator('#viewport canvas').evaluate(canvas=>{canvas.tabIndex=-1;canvas.focus();});
    await page.goto(url);
    await page.waitForFunction(()=>!!window.marsClient);
    await closeLobby();
    await page.waitForFunction(()=>document.querySelector('#connection').dataset.connected==='true');
    assert.equal(await page.locator('#network-wait').isVisible(),false);
    assert.equal(await page.locator('#panel-toggle,#instruments').count(),0);
    assert.equal(await page.locator('#settings-toggle').getAttribute('aria-label'),'Настройки');
    assert.equal(await page.locator('#settings-toggle').innerText(),'');
    assert.equal(await page.locator('#settings-toggle').evaluate(el=>el.nextElementSibling.matches('.player-chip')),true);
    // Capture the existing scene through the same dev module, without a production debug API.
    await page.evaluate(async()=>{
      const {WorldScene}=await import('/src/scene/world-scene.js');
      const select=WorldScene.prototype.select;
      WorldScene.prototype.select=function(...args){window.hudTestScene=this;return select.apply(this,args);};
      window.marsClient.events.emit('build.type',null);
      window.hudTestBuildCommands=[];
      window.marsClient.events.on('command',command=>window.hudTestBuildCommands.push(command));
      // Geometry fixtures have no economy/stage DTO; supply a HUD snapshot for price checks.
      window.marsClient.events.emit('world.state',{stage:'running',team_storage:{iron:40,sulfur:15,water:5,copper:0},config:{storage_capacity:300,recipes:{drill:{iron:5},oxygen_generator:{iron:15,sulfur:5},warehouse:{iron:10,sulfur:5},dome_base:{iron:10}}}});
      window.hudTestScene.controls.pitch=-.6;
    });
    await page.waitForFunction(()=>!!window.hudTestScene.selected);
    assert.equal(await selected(),0);
    assert.equal(await page.locator('#build-context').isVisible(),false);
    assert.equal(await page.evaluate(()=>window.hudTestScene.preview.visible),false);
    assert.equal(await page.locator('#performance').isVisible(),false);
    assert.equal(await page.locator('#performance-detail').isVisible(),false);
    assert.equal(await page.locator('#cache').isVisible(),false);
    assert.equal(await page.locator('#colors,#building').count(),0);
    assert.doesNotMatch(await page.locator('body').innerText(),/ЛОКАЛЬНАЯ СЕТЬ/i);
    await focusGame();await page.keyboard.press('b');
    assert.equal(await selected(),0);
    await screenshot('desktop-explore');
    const types=['drill','oxygen_generator','warehouse','dome_base'];
    for(let i=0;i<types.length;i++){
      await page.keyboard.press(String(i+1));
      assert.equal(await page.locator(`[data-building="${types[i]}"]`).getAttribute('aria-pressed'),'true');
      assert.equal(await page.locator('#build-context').isVisible(),true);
      assert.equal(await page.evaluate(()=>window.hudTestScene.buildType),types[i]);
      assert.equal(await page.evaluate(()=>window.hudTestScene.preview.visible),true);
    }
    await screenshot('desktop-build');
    await page.keyboard.press('4');assert.equal(await selected(),0);
    assert.equal(await page.evaluate(()=>window.hudTestScene.preview.visible),false);
    await page.keyboard.press('1');await page.keyboard.press('Escape');assert.equal(await selected(),0);
    await page.locator('[data-building="warehouse"]').click();assert.equal(await selected(),1);
    await page.locator('#build-cancel').click();assert.equal(await selected(),0);
    await focusGame();await page.keyboard.press('3');
    await page.locator('#assistant-toggle').click();await focusGame();
    await page.keyboard.press('Escape');assert.equal(await selected(),1);
    assert.equal(await page.locator('#assistant-panel').isVisible(),false);
    await page.keyboard.press('Escape');assert.equal(await selected(),0);
    await focusGame();await page.keyboard.press('h');assert.equal(await page.locator('#instruments').count(),0);
    assert.equal(await page.locator('#build-hotbar').isVisible(),true);
    await page.locator('#settings-toggle').click();
    assert.equal(await page.evaluate(()=>window.hudTestScene.controls.suspended),true);
    const mode=await page.evaluate(()=>window.hudTestScene.mode);
    await page.keyboard.press('1');await page.keyboard.press('h');await page.keyboard.press('Tab');
    assert.equal(await selected(),0);
    assert.equal(await page.locator('#instruments').count(),0);
    assert.equal(await page.evaluate(()=>window.hudTestScene.mode),mode);
    await page.locator('#quality').selectOption('low');
    for(const id of ['stars','rocks','dust','animations'])await page.locator('#'+id).uncheck();
    assert.equal(await page.locator('#camera-bob').isDisabled(),true);
    await page.locator('#show-fps').check();
    await page.locator('#show-diagnostics').check();
    assert.deepEqual(await page.evaluate(()=>{
      const {stars,rocks,dust,animations}=window.hudTestScene.visualOptions;
      return {stars,rocks,dust,animations};
    }),{stars:false,rocks:false,dust:false,animations:false});
    await screenshot('desktop-settings');
    await page.keyboard.press('Escape');
    await page.locator('#game-settings').waitFor({state:'hidden'});
    await page.waitForFunction(()=>!window.hudTestScene.controls.suspended);
    assert.equal(await page.evaluate(()=>window.hudTestScene.controls.suspended),false);
    for(const id of ['performance','performance-detail','cache'])assert.equal(await page.locator('#'+id).isVisible(),true);
    await page.locator('.player-chip').click();
    await page.locator('.edit-profile').click();
    const original=await page.locator('.avatar-editor img').getAttribute('src');
    assert.equal(await page.locator('.save-profile').isDisabled(),true);
    await page.locator('.shuffle-avatar').click();
    assert.notEqual(await page.locator('.avatar-editor img').getAttribute('src'),original);
    await page.keyboard.press('2');assert.equal(await selected(),0);
    await page.locator('.cancel-profile-text').click();
    await page.locator('.edit-profile').click();
    assert.equal(await page.locator('.avatar-editor img').getAttribute('src'),original);
    await page.locator('.shuffle-avatar').click();
    const saved=await page.locator('.avatar-editor img').getAttribute('src');
    await screenshot('desktop-profile');
    await page.locator('.save-profile').click();
    assert.equal(await page.locator('.pilot-avatar').getAttribute('src'),saved);
    await page.reload();await page.waitForFunction(()=>!!window.marsClient);
    assert.equal(await page.locator('.pilot-avatar').getAttribute('src'),saved);
    await closeLobby();
    await page.locator('#settings-toggle').click();
    assert.equal(await page.locator('#quality').inputValue(),'low');
    for(const id of ['stars','rocks','dust','animations'])assert.equal(await page.locator('#'+id).isChecked(),false);
    for(const id of ['show-fps','show-diagnostics'])assert.equal(await page.locator('#'+id).isChecked(),true);
    await page.locator('#animations').check();
    assert.equal(await page.locator('#camera-bob').isDisabled(),false);
    await page.locator('#camera-bob').uncheck();
    await page.locator('#show-fps').uncheck();await page.locator('#show-diagnostics').uncheck();
    await page.locator('.settings-done').click();
    await page.setViewportSize({width:390,height:844});
    await page.locator('[data-building="drill"]').click();
    await screenshot('mobile-build');
    const checkBounds=async selector=>{
      const box=await page.locator(selector).boundingBox();
      assert.ok(box && box.x>=-1 && box.x+box.width<=391,`${selector} escapes mobile viewport: ${JSON.stringify(box)}`);
    };
    for(const selector of ['#build-hotbar','#build-context','#connection','#settings-toggle','.player-chip'])await checkBounds(selector);
    await page.locator('#settings-toggle').click();await screenshot('mobile-settings');await checkBounds('#game-settings');
    await page.locator('.settings-done').click();
    await page.locator('.player-chip').click();await page.locator('.edit-profile').click();
    await screenshot('mobile-profile');await checkBounds('.player-lobby');
    await page.locator('.cancel-profile-text').click();await closeLobby();
    await page.evaluate(()=>window.marsClient.events.emit('connection.status','reconnecting'));
    await closeLobby();
    assert.equal(await page.locator('#network-wait').innerText(),'ОЖИДАНИЕ СЕТИ');
    assert.equal(await page.locator('#network-wait').isVisible(),true);
    assert.equal(await page.locator('.network-dot').evaluate(el=>getComputedStyle(el).backgroundColor),'rgb(255, 98, 94)');
    await screenshot('mobile-network-wait');
    await page.evaluate(()=>window.marsClient.events.emit('connection.status','connected'));
    assert.equal(await page.locator('#network-wait').isVisible(),false);
    assert.equal(await page.locator('.network-dot').evaluate(el=>getComputedStyle(el).backgroundColor),'rgb(101, 221, 151)');
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true);
    assert.deepEqual(errors,[]);
    console.log('PASS: building shortcuts/cancel, no H panel, settings icon/order, network disconnect/reconnect, settings persistence, profile save/cancel, desktop/mobile; no JS errors.');
    console.log('Screenshots: '+output);
  } finally {await browser.close();}
})().catch(error=>{console.error(error);process.exit(1);});
